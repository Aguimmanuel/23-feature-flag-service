import {
  test,
  expect,
  type Page,
  type APIRequestContext,
} from "@playwright/test";
import { randomUUID } from "node:crypto";
import { mkdirSync } from "node:fs";

// Credentials come from the test process, never VITE_* variables or fixtures.
const token = process.env.ADMIN_TOKEN;
if (!token)
  throw new Error(
    "Set ADMIN_TOKEN privately before running local real-backend tests.",
  );
const headers = { Authorization: `Bearer ${token}` };
const keys: string[] = [];
const newKey = () => {
  const key = `ui-test-${randomUUID().slice(0, 8)}`;
  keys.push(key);
  return key;
};
async function login(page: Page, credential = token!) {
  await page.goto("/");
  await page.getByLabel("Administrator token").fill(credential);
  await page.getByRole("button", { name: "Open dashboard →" }).click();
}
async function create(request: APIRequestContext, key: string) {
  const response = await request.post("/api/v1/flags", {
    headers,
    data: { key, description: "Disposable local UI integration check" },
  });
  expect(response.status()).toBe(201);
}
async function select(page: Page, key: string) {
  await page.getByRole("button", { name: new RegExp(key) }).click();
  await expect(page.getByLabel("Environment")).toHaveValue("development");
}
test.beforeAll(async ({ request }) => {
  expect((await request.get("/health/ready")).status()).toBe(200);
});
test.afterEach(async ({ request }) => {
  // Only keys generated by this test run are archived. No tables are truncated.
  for (const key of keys.splice(0)) {
    const response = await request.delete(`/api/v1/flags/${key}`, { headers });
    expect([204, 404]).toContain(response.status());
  }
});

