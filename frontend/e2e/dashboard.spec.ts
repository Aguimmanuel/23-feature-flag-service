test("real stale version preserves input and reloads rather than overwriting", async ({
  page,
  request,
}) => {
  const key = newKey();
  await create(request, key);
  await login(page);
  await select(page, key);
  await page.getByLabel("Target groups").fill("my-unsaved-group");
  // Simulate a second administrator saving the same version first.
  const updated = await request.put(
    `/api/v1/flags/${key}/environments/development`,
    {
      headers,
      data: {
        enabled: true,
        target_groups: ["other-admin"],
        rollout_percentage: 0,
        version: 1,
      },
    },
  );
  expect(updated.status()).toBe(200);
  await page.getByRole("button", { name: "Save configuration" }).click();
  await expect(
    page.getByRole("button", { name: "Reload latest configuration" }),
  ).toBeVisible();
  await expect(page.getByLabel("Target groups")).toHaveValue(
    "my-unsaved-group",
  );
  await expect(
    page.getByRole("button", { name: "Save configuration" }),
  ).toBeDisabled();
  await page
    .getByRole("button", { name: "Reload latest configuration" })
    .click();
  await expect(page.getByLabel("Target groups")).toHaveValue("other-admin");
});

